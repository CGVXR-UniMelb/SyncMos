# 🔧 Definition"Harmless cleanup actions"Mode: These additional actions should not be considered test failures
# These actions are typically reasonable cleanup actions generated by the LLM/Stop action
# Note: This rule is only applied when no expected events are matched
HARMLESS_CLEANUP_PATTERNS = [
    # Stop-like actions (the most common additional cleanup actions)
    r"^stop\s+",  # stop drinking, stop eating, stop waving, etc.
    r"^end\s+",  # end phone call, end conversation, etc.
    r"^finish\s+",  # finish reading, finish typing, etc.
    r"^cease\s+",  # cease activity
    # Putting down/Cleanup-like actions (individual or combined)
    # Only put down actions that do not match expected events are considered cleanup actions
    r"^put\s+down\s+(the\s+)?\w+",  # put down bottle, put down the food, etc.
    r"^place\s+down\s+(the\s+)?\w+",
    r"^set\s+down\s+(the\s+)?\w+",
    r"^place\s+(the\s+)?\w+\s+(on|down)",
    # Turn off/End-like actions
    r"^turn\s+off\s+(the\s+)?(light|computer|laptop|device|phone)",
    r"^close\s+(the\s+)?(book|laptop|document)",
    r"^hang\s+up\s+(the\s+)?phone",
]


def is_harmless_cleanup_action(activity: str) -> bool:
    """Determine whether an action is a harmless cleanup action/Cleanup actions

    Args:
        activity: Action description string

    Returns:
        Return True if it’s a harmless ending action; otherwise, return False

    Example:
        >>> is_harmless_cleanup_action("stop drinking")
        True
        >>> is_harmless_cleanup_action("put down the bottle and food")
        True
        >>> is_harmless_cleanup_action("pick up bottle")
        False
    """
    if not activity:
        return False

    activity_lower = activity.lower().strip()

    # Check if it matches any ending action patterns
    for pattern in HARMLESS_CLEANUP_PATTERNS:
        if re.match(pattern, activity_lower):
            return True

    return False


def are_actions_equivalent(action1: str, action2: str) -> bool:
    """Determine whether the two action phrases are semantically equivalent

    Args:
        action1: The first action phrase (e.g.) "get up", "stand up")
        action2: The second action phrase

    Returns:
        If the two actions are semantically equivalent, return True

    Example:
        >>> are_actions_equivalent("get up", "stand up")
        True
        >>> are_actions_equivalent("pick up", "grab")
        True
    """
    a1_lower = action1.lower().strip()
    a2_lower = action2.lower().strip()

    # Direct matching
    if a1_lower == a2_lower:
        return True

    # Check synonyms
    for canonical, synonyms in ACTION_SYNONYMS.items():
        if a1_lower in synonyms and a2_lower in synonyms:
            return True

    return False


def match_activity_with_or_options(generated_activity: str, expected_activity: str) -> bool:
    """Compare the generated activity with the expected activity, supporting (option1 | option2 | option3) Format and keyword matching

    Args:
        generated_activity: The generated activity string
        expected_activity: The expected activity string, which may contain (option1 | option2 | option3) Format

    Returns:
        If it matches, return True; otherwise, return False

    Example:
        expected: "sit down on (chair2 | chair_4 | chair_5 | chair_6) in the dining area"
        generated: "sit down on chair_4 in the dining area" -> True
        generated: "sit down on chair2 in the dining area" -> True

        expected: "pick up"  # Short action label
        generated: "pick up a bottle near the bar" -> True
    """
    if not generated_activity or not expected_activity:
        return generated_activity == expected_activity

    generated_lower = generated_activity.lower().strip()
    expected_lower = expected_activity.lower().strip()

    # Two-way matching: Matches are considered when the generated content matches the expected content
    # This allows handling situations where the generated activities are more detailed (or more concise) than expected
    if expected_lower in generated_lower or generated_lower in expected_lower:
        return True

    # 🔧 Quick fix 1: Semantic equivalence check (synonyms for actions)
    # Extract the first 2-3 Each word is used as a synonym for an action phrase
    # However, this is only used when the expected activity itself is a phrase (<=(2 words) are used only when the expected activity is a 2-word phrase
    gen_words = generated_lower.split()
    exp_words = expected_lower.split()

    if len(gen_words) >= 2 and len(exp_words) >= 2 and len(exp_words) <= 2:
        # Try 2 Phrase (e.g "pick up", "hand over")
        # Matches only when the expected activity is a 2-word phrase
        gen_action_2 = " ".join(gen_words[:2])
        exp_action_2 = " ".join(exp_words[:2])
        if are_actions_equivalent(gen_action_2, exp_action_2):
            # Action equivalence is considered a match
            return True

    # Try Word Action (e.g "drink", "receive")
    # But note: Word matching is only used when the expected value has only 1 word-2 Word matching is used only when the expected value consists of 1 word
    # Avoiding Error Matching Multiword phrases (e.g "turn on" vs "turn off")
    if len(gen_words) >= 1 and len(exp_words) >= 1:
        # If expected is a multiword phrase (e.g "turn off light"),
        # But the first two words don’t match (e.g "turn on" vs "turn off"),
        # You should not return on the first word True
        if len(exp_words) >= 2 and len(gen_words) >= 2:
            # It’s a multiword phrase, already on top 2 It’s been processed in the word phrase check
            # If there’s no match up here, it shouldn’t be
            pass
        else:
            # Word action or one of them is a word
            if are_actions_equivalent(gen_words[0], exp_words[0]):
                # First word equals the price
                return True

    # 🔧 Fast fix 2: Keyword Match (No order required, as long as all words appeared)
    # For example: expected="receive bottle from Amir", "pick up", "hand over"
    # Allows extra words in generated (It’s like a title, qualifier, location information, etc)

    # Define disabled words that need filtering (Advertisements, crowns, common qualifiers)
    STOP_WORDS = {
        "the",
        "a",
        "an",  # Title
        "at",
        "on",
        "in",
        "from",
        "to",
        "with",
        "by",
        "of",  # Prepositions
        "using",
        "near",
        "onto",  # Common modifiers
    }

    expected_words = expected_lower.split()
    # Filter out stopwords and names (words in capital letters are usually names, which should be handled by character matching)
    # Note: We need to check whether the first letter is capitalized before converting to lowercase
    original_words = expected_activity.split()
    expected_keywords = [
        w
        for w, orig in zip(expected_words, original_words)
        if w not in STOP_WORDS and not orig[0].isupper()  # Filter out stopwords and names
    ]

    # Increase the threshold to 6 words to support more complex activity descriptions
    # Exclude cases with the or option (that situation is handled by subsequent logic)
    if len(expected_keywords) <= 6 and "(" not in expected_lower:
        # Check whether all keywords appear in the generated text (word-level matching, no order requirement)
        # Split the generated activities into words for word-level matching
        gen_words_set = set(generated_lower.split())

        # Simple stemming: remove common endings (-s, -es, -ed, -ing)
        # This allows for matching pick/picks/picked/picking
        def simple_stem(word: str) -> str:
            """Simple stemming, removing common endings"""
            if len(word) <= 3:
                return word

            # Process endings by priority (from long to short, avoid incorrect truncation)
            # 1. Remove -ing
            if word.endswith("ing") and len(word) > 4:
                base = word[:-3]
                # Process double consonants (e.g., putting) -> put, running -> run)
                if len(base) >= 2 and base[-1] == base[-2] and base[-1] not in "aeiou":
                    return base[:-1]
                # If removed, add back after 'v' Ending with, need to add back 'e' (receiving -> receive)
                if base.endswith("v"):
                    return base + "e"
                return base

            # 2. Remove -ed
            if word.endswith("ed") and len(word) > 3:
                base = word[:-2]
                # If removed, add back after 'v' Ending with, need to add back 'e' (received -> receive)
                if base.endswith("v"):
                    return base + "e"
                return base

            # 3. Remove -es (But be careful not to remove part of the root)
            # Such as "receives" -> "receive", Instead of "receiv"
            if word.endswith("es") and len(word) > 4:
                # Check if it’s -ves, -ses, -xes, -zes, -ches, -shes ending with
                # In these cases -es It’s plural marker
                if word[-3] in "sxz" or word[-4:-2] in ["ch", "sh"]:
                    return word[:-2]
                # Otherwise, it might be the third person singular of a verb. Try to remove it -s
                return word[:-1]

            # 4. Remove -s (But avoiding removal is itself -ss Words at the end)
            if word.endswith("s") and len(word) > 2 and not word.endswith("ss"):
                return word[:-1]

            return word

        # Stemming the generated set of words
        gen_words_stemmed = {simple_stem(w) for w in gen_words_set}

        # Checking whether each expected keyword (after stemming) is present in the generated set of words
        # Using substring matching to match "receiv" It can be matched "receive"
        def word_matches(exp_word: str, gen_stems: set) -> bool:
            exp_stem = simple_stem(exp_word)
            # Exact matching
            if exp_stem in gen_stems:
                return True
            # Substring matching: exp_stem is in some gen_stem, or gen_stem is in exp_stem
            for gen_stem in gen_stems:
                if exp_stem in gen_stem or gen_stem in exp_stem:
                    return True
            # Synonym matching for objects: checking whether they are synonyms
            if exp_word in OBJECT_SYNONYMS:
                synonyms = OBJECT_SYNONYMS[exp_word]
                for synonym in synonyms:
                    synonym_stem = simple_stem(synonym)
                    if synonym_stem in gen_stems:
                        return True
                    # Also checking substring matching
                    for gen_stem in gen_stems:
                        if synonym_stem in gen_stem or gen_stem in synonym_stem:
                            return True
            return False

        all_words_found = all(
            word_matches(word, gen_words_stemmed) for word in expected_keywords
        )  # Using the filtered keywords

        if all_words_found:
            # All expected keywords have been found
            return True

    # Searching for all (option1 | option2 | ...) Format segment
    or_pattern = r"\(([^)]+(?:\s*\|\s*[^)]+)+)\)"
    or_matches = list(re.finditer(or_pattern, expected_lower))

    if not or_matches:
        # No or option, direct string matching
        return generated_lower == expected_lower

    # With or option: Construct regular expressions using placeholder methods
    placeholders = []
    regex_pattern = expected_lower

    # Replace from back to front to avoid index changes
    for i, match in enumerate(reversed(or_matches)):
        start, end = match.span()
        content = match.group(1)
        # Split option, remove spaces, escape special characters
        options = [re.escape(opt.strip()) for opt in content.split("|")]
        # Create placeholders
        placeholder = f"__OR_PLACEHOLDER_{i}__"
        placeholders.append(("(" + "|".join(options) + ")", placeholder))
        regex_pattern = regex_pattern[:start] + placeholder + regex_pattern[end:]

    # Escape other characters (placeholders will be escaped, but we can recognize them)
    regex_pattern = re.escape(regex_pattern)

    # Restore placeholders to regular expression selection mode
    for pattern, placeholder in placeholders:
        escaped_placeholder = re.escape(placeholder)
        regex_pattern = regex_pattern.replace(escaped_placeholder, pattern)

    # Use regular expressions for matching (partial matching allowed, as the generated activity may have additional descriptions)
    try:
        # Usage ^ and $ Ensure full matching, or use search with partial matching allowed
        # Use search here, as the generated activity may contain additional descriptions
        return bool(re.search(regex_pattern, generated_lower))
    except re.error:
        # If the regular expression has issues, fall back to simple matching
        return generated_lower == expected_lower


def fuzzy_match_activity(
    generated: str, expected: str, alternatives: List[str] = None, required_keywords: List[str] = None
) -> Tuple[bool, float]:
    """Fuzzy matching for activity descriptions, supports semantically equivalent expressions

    This function is more flexible than match_activity_with_or_options and can handle more complex scenarios:
    - Semantically equivalent alternative expressions
    - Keyword matching (no exact match required)
    - Returns a confidence score

    Args:
        generated: Generated Activity Descriptions
        expected: Desired activity description
        alternatives: List of semantically equivalent alternatives (optional)
        required_keywords: List of required keywords (optional)

    Returns:
        (is_match, confidence_score)
        - is_match: Whether there is a match
        - confidence_score: Confidence level (0.0-1.0)

    Examples:
        >>> fuzzy_match_activity("sit on chair", "sit down on chair")
        (True, 0.9)

        >>> fuzzy_match_activity(
        ...     "take a seat on chair_2",
        ...     "sit down on chair_2",
        ...     alternatives=["sit on chair_2", "take a seat on chair_2"]
        ... )
        (True, 0.95)
    """
    if not generated or not expected:
        return (generated == expected), 1.0 if generated == expected else 0.0

    generated_lower = generated.lower().strip()
    expected_lower = expected.lower().strip()

    # 1. Exact match (highest confidence level)
    if expected_lower in generated_lower:
        return True, 1.0

    # If the generated result is within the expected range, generate a more concise version)
    if generated_lower in expected_lower:
        return True, 0.95

    # 2. Matching Subexpressions
    if alternatives:
        for alt in alternatives:
            alt_lower = alt.lower().strip()
            if alt_lower in generated_lower or generated_lower in alt_lower:
                return True, 0.9

    # 3. Keyword Matching
    if required_keywords:
        matched = sum(1 for kw in required_keywords if kw.lower() in generated_lower)
        keyword_confidence = matched / len(required_keywords)

        if keyword_confidence >= 0.8:  # 80% Keyword Matching
            return True, 0.7 + keyword_confidence * 0.2  # 0.7-0.9
        elif keyword_confidence >= 0.5:  # 50-80% Match
            return False, keyword_confidence  # Partial match, not passing the full criteria

    # 4. Extract and compare key verbs and nouns (simplified version)
    # Extract action words (sit), stand, walk, pick, put, hand, receive, drink, etc.)
    action_verbs = [
        "sit",
        "stand",
        "walk",
        "pick",
        "put",
        "hand",
        "receive",
        "drink",
        "eat",
        "read",
        "write",
        "type",
        "play",
        "listen",
    ]

    expected_verbs = [v for v in action_verbs if v in expected_lower]
    generated_verbs = [v for v in action_verbs if v in generated_lower]

    if expected_verbs and generated_verbs:
        # Check if the main actions match
        if any(v in generated_verbs for v in expected_verbs):
            # Actions match, but the objects may differ
            return False, 0.4  # Partial Matching

    # 5. No match found
    return False, 0.0


def extract_activity_keywords(activity: str) -> List[str]:
    """Extract keywords from the activity description

    The extracted keywords include:
    - Action word (sit), walk, pick, etc.)
    - Object name (chair), table, bottle, etc.)
    - Location word (dining area), bar, etc.)

    Args:
        activity: Activity description string

    Returns:
        List of Keywords

    Example:
        >>> extract_activity_keywords("sit down on chair_2 in the dining area")
        ['sit', 'chair', 'dining']
    """
    if not activity:
        return []

    activity_lower = activity.lower()

    # Common action words
    action_verbs = [
        "sit",
        "stand",
        "walk",
        "pick",
        "put",
        "hand",
        "receive",
        "drink",
        "eat",
        "read",
        "write",
        "type",
        "play",
        "listen",
        "move",
        "go",
        "come",
        "take",
        "give",
        "hold",
        "grab",
    ]

    # Common object types
    objects = ["chair", "table", "desk", "sofa", "bed", "bottle", "cup", "book", "phone", "laptop", "door", "window"]

    # Common location words
    locations = ["dining", "kitchen", "bedroom", "office", "bar", "area", "room"]

    keywords = []

    # Extract action words
    for verb in action_verbs:
        if verb in activity_lower:
            keywords.append(verb)

    # Extract objects
    for obj in objects:
        if obj in activity_lower:
            keywords.append(obj)

    # Extract positions
    for loc in locations:
        if loc in activity_lower:
            keywords.append(loc)

    # Extract object IDs (e.g., chair_2), table_1)
    obj_id_pattern = r"(chair|table|sofa|desk)_?\d+"
    obj_ids = re.findall(obj_id_pattern, activity_lower)
    keywords.extend(obj_ids)

    return list(set(keywords))  # Remove duplicates


def match_activity_with_fuzzy_option(
    generated_activity: str, expected_activity: str, use_fuzzy: bool = True, fuzzy_threshold: float = 0.7
) -> bool:
    """Comprehensive method combining exact matching and fuzzy matching

    First try exact matching (supports or option). If failed, use fuzzy matching.

    Args:
        generated_activity: Generated Activity Descriptions
        expected_activity: Desired activity description
        use_fuzzy: Whether to use fuzzy matching as a backup
        fuzzy_threshold: Confidence threshold for fuzzy matching

    Returns:
        Whether there is a match

    Example:
        >>> match_activity_with_fuzzy_option(
        ...     "sitting on chair_2",
        ...     "sit down on chair_2"
        ... )
        True
    """
    # 1. First try exact matching (supports or option)
    if match_activity_with_or_options(generated_activity, expected_activity):
        return True

    # 2. If no fuzzy matching is used, return directly
    if not use_fuzzy:
        return False

    # 3. Using fuzzy matching
    keywords = extract_activity_keywords(expected_activity)
    matched, confidence = fuzzy_match_activity(generated_activity, expected_activity, required_keywords=keywords)

    return confidence >= fuzzy_threshold


def infer_action_label(activity: str, available_labels: List[str]) -> str | None:
    if not activity:
        return None
    act = activity.lower().replace("_", " ")
    for label in available_labels:
        l = label.lower()
        if l in act or l.replace("_", " ") in act:
            return label
    return None


def collect_timeline_events(narrator, extra_events: Optional[object] = None) -> List[Event]:
    events: List[Event] = []

    def add_event(ev):
        if ev is None:
            return
        if isinstance(ev, (list, tuple)):
            for item in ev:
                add_event(item)
            return
        if isinstance(ev, Event):
            events.append(ev)
        elif isinstance(ev, ParallelEventGroup):
            events.extend(ev.events)

    for ev in getattr(narrator, "event_list", []) or []:
        add_event(ev)
    for ev in getattr(narrator, "previous_events", []) or []:
        add_event(ev)
    add_event(extra_events)

    # Remove duplicates (by event_id)
    unique_events: List[Event] = []
    seen_ids = set()
    for ev in events:
        tl_data = getattr(ev, "timeline_data", {}) or {}
        event_id = tl_data.get("event_id")
        if event_id:
            if event_id in seen_ids:
                continue
            seen_ids.add(event_id)
        unique_events.append(ev)

    return unique_events


def collect_actions_from_timeline(
    narrator, available_action_labels: List[str], extra_events: Optional[object] = None
) -> Dict[str, List[str]]:
    actions: Dict[str, List[str]] = {}
    for e in collect_timeline_events(narrator, extra_events):
        chars = [c.name for c in getattr(e, "involved_characters", [])]
        act = getattr(e, "activity", "")
        label = infer_action_label(act, available_action_labels)
        if not label:
            continue
        for name in chars:
            actions.setdefault(name, []).append(label)
    return actions


def evaluate_next_event_action(
    test_case: dict,
    actions_by_character: Dict[str, List[str]],
    generated_characters: List[str] | None = None,
    generated_event: any = None,
) -> bool:
    if not test_case:
        return True
    exp = test_case.get("expected_next_event")

    # An empty dictionary or None indicates a null expectation (no events)
    if not exp or exp == {}:
        # Expected null: The generated result should also be None or empty
        return generated_event is None and (generated_characters is None or len(generated_characters) == 0)

    # Parallel: only characters set equality
    if isinstance(exp.get("characters"), list) and not exp.get("activity"):
        if generated_characters is None:
            return False
        return set(map(str, generated_characters)) == set(map(str, exp["characters"]))

    # Single event: Check character matching
    ch = exp.get("character")
    if not ch:
        return False

    # Check if characters match
    if generated_characters is None or ch not in generated_characters:
        return False

    # If there is an activity field, directly compare the activity (supports or option)
    if "activity" in exp:
        if generated_event is None:
            return False
        generated_activity = getattr(generated_event, "activity", "")
        expected_activity = exp.get("activity", "")
        if not expected_activity:
            return True  # If there is no expected activity, pass if character matching is sufficient

        # Use match_activity_with_or_options for comparison (supported) (option1 | option2 | option3) Format)
        return match_activity_with_or_options(generated_activity, expected_activity)

    # If there is no activity field, pass if character matching is sufficient
    return True


def evaluate_timeline_actions(narrator, test_case: dict, extra_events: Optional[object] = None) -> bool:
    """Evaluate the coverage and dependency relationships of the activity in the timeline

    1. Compare the events generated by activity matching with the expected events (supports or option)
    2. Check if the event_id of the successfully matched events is consistent with the expected event_id
    3. Check if the generated dependencies are consistent with the expected dependencies
    """
    et = (test_case or {}).get("expected_timeline", {})
    expected_events = et.get("events", [])
    expected_dependencies = et.get("dependencies", [])

    if not expected_events:
        return True

    # Obtain the list of generated events and dependencies from the narrator
    generated_events = collect_timeline_events(narrator, extra_events)
    generated_dependencies = getattr(narrator, "timeline_dependencies", []) or []

    # Step 1: Compare the events generated by activity matching with the expected events
    # Construct the generated_event -> Map the expected_event
    matched_events = {}  # generated_event_id -> expected_event_id
    matched_expected = set()  # Matched expected_event_id

    for gen_event in generated_events:
        generated_activity = getattr(gen_event, "activity", "")
        if not generated_activity:
            continue

        tl_data = getattr(gen_event, "timeline_data", {}) or {}
        generated_event_id = tl_data.get("event_id", "")
        if not generated_event_id:
            continue

        # Attempted to match the expected event
        for exp_event in expected_events:
            expected_event_id = exp_event.get("event_id")
            if not expected_event_id or expected_event_id in matched_expected:
                continue

            expected_activity = exp_event.get("activity", "")
            if not expected_activity:
                continue

            # Matched by activity (supports or option)
            if match_activity_with_or_options(generated_activity, expected_activity):
                matched_events[generated_event_id] = expected_event_id
                matched_expected.add(expected_event_id)
                break

    # Step 2: Check if event_id are consistent
    # If the match by activity is successful, ensure the generated event_id matches the expected event_id
    event_id_ok = True
    for generated_event_id, expected_event_id in matched_events.items():
        if generated_event_id != expected_event_id:
            event_id_ok = False
            break

    # Step 3: Check if dependencies are consistent
    # Only check the dependencies of events that have been matched by activity and have consistent event_id
    def normalize_dep(dep):
        """Standardize dependencies for comparison"""
        if not isinstance(dep, dict):
            return None
        if "parallel" in dep:
            grp = dep.get("parallel", [])
            if not isinstance(grp, list) or not grp:
                return None
            return ("parallel", frozenset(sorted(grp)))
        else:
            a = dep.get("after")
            b = dep.get("before")
            if not a or not b:
                return None
            return ("order", a, b)

    # Obtain all valid matching event_id (those that have been matched by activity and have consistent event_id)
    valid_event_ids = {gen_id for gen_id, exp_id in matched_events.items() if gen_id == exp_id}

    # Standardize the expected dependencies
    expected_dep_set = set()
    for dep in expected_dependencies:
        normalized = normalize_dep(dep)
        if normalized:
            # Only consider dependencies where the involved event_id are in the valid_event_ids
            if normalized[0] == "parallel":
                _, ids = normalized
                if all(eid in valid_event_ids for eid in ids):
                    expected_dep_set.add(normalized)
            elif normalized[0] == "order":
                _, after_id, before_id = normalized
                if after_id in valid_event_ids and before_id in valid_event_ids:
                    expected_dep_set.add(normalized)

    # Standardize the generated dependencies (only consider events within valid_event_ids)
    generated_dep_set = set()
    for dep in generated_dependencies:
        normalized = normalize_dep(dep)
        if not normalized:
            continue

        # Only consider dependencies where the involved event_id is within valid_event_ids
        if normalized[0] == "parallel":
            _, gen_ids = normalized
            if all(gid in valid_event_ids for gid in gen_ids):
                generated_dep_set.add(normalized)
        elif normalized[0] == "order":
            _, gen_after, gen_before = normalized
            if gen_after in valid_event_ids and gen_before in valid_event_ids:
                generated_dep_set.add(normalized)

    # Check whether the generated dependencies include all expected dependencies
    dependency_ok = expected_dep_set.issubset(generated_dep_set)

    # Also check whether all expected events have been matched
    all_expected_matched = len(matched_expected) == len(expected_events)

    return event_id_ok and dependency_ok and all_expected_matched


def evaluate_timeline_actions_with_diagnostics(
    narrator, test_case: dict, extra_events: Optional[object] = None
) -> Tuple[bool, dict]:
    """Evaluate the timeline and return detailed diagnostic information

    Returns:
        (actions_ok, diagnostics): Tuple containing evaluation results and detailed diagnostic information
    """
    et = (test_case or {}).get("expected_timeline", {})
    expected_events = et.get("events", [])

    diagnostics = {
        "generated_events": [],
        "generated_dependencies": [],
        "matched_characters": [],
        "activity_mismatches": [],
        "actions_ok": False,
    }

    if not expected_events:
        diagnostics["actions_ok"] = True
        return True, diagnostics

    # Obtain the list of generated events and dependencies from the narrator
    generated_events = collect_timeline_events(narrator, extra_events)
    generated_dependencies = getattr(narrator, "timeline_dependencies", []) or []

    # Record the generated events
    for gen_event in generated_events:
        tl_data = getattr(gen_event, "timeline_data", {}) or {}
        diagnostics["generated_events"].append(
            {
                "event_id": tl_data.get("event_id", ""),
                "character": next((c.name for c in getattr(gen_event, "involved_characters", [])), "?"),
                "activity": getattr(gen_event, "activity", ""),
            }
        )

    # Record the generated dependencies
    for dep in generated_dependencies:
        diagnostics["generated_dependencies"].append(dep)

    # Organize expected activities by character
    expected_activities_by_character = {}
    for exp_event in expected_events:
        char = exp_event.get("character")
        activity = exp_event.get("activity", "")
        if char not in expected_activities_by_character:
            expected_activities_by_character[char] = []
        expected_activities_by_character[char].append(activity)

    # Organize generated activities by character
    generated_activities_by_character = {}
    for gen_event in generated_events:
        char_names = [c.name for c in getattr(gen_event, "involved_characters", [])]
        activity = getattr(gen_event, "activity", "")
        for char in char_names:
            if char not in generated_activities_by_character:
                generated_activities_by_character[char] = []
            generated_activities_by_character[char].append(activity)

    # Check the activities for each character
    all_matched = True
    for char, expected_activities in expected_activities_by_character.items():
        generated_activities = generated_activities_by_character.get(char, [])

        # Simple check: For each expected activity, there is at least one generated activity that matches
        char_matched = True
        for exp_act in expected_activities:
            found_match = False
            for gen_act in generated_activities:
                if match_activity_with_or_options(gen_act, exp_act):
                    found_match = True
                    break

            if not found_match:
                char_matched = False
                all_matched = False
                diagnostics["activity_mismatches"].append(
                    {
                        "character": char,
                        "expected": expected_activities,
                        "generated": generated_activities,
                        "issue": f"No match found for expected activity: {exp_act}",
                    }
                )
                break

        if char_matched:
            diagnostics["matched_characters"].append(char)

    diagnostics["actions_ok"] = all_matched
    return all_matched, diagnostics
